
package com.snhu.mscs.cs600.salesguru.sales;

import jakarta.persistence.*;

/**
 * LineItem -
 *
 * Purpose:
 *      Represents an individual product associated with an invoice.
 *      Each record stores the product, quantity, and discount.
 *
 *      This class maps to the line_items table in the SalesGuru database.
 *
 * Version              Author          Date            Description
 * ***********************************************************************
 *     1                 Chris Bright   17-Nov-2026     Initial Creation
 */
@Entity
@Table(name = "line_items")
public class LineItem {

  /**
   * Unique primary key generated by PostgreSQL.
   */
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  @Column(name = "line_item_id")
  private Integer lineItemId;

  /**
   * Identifies the invoice containing this line item.
   */
  @Column(name = "invoice_number", nullable = false)
  private Integer invoiceNumber;

  /**
   * Identifies the product being sold.
   */
  @Column(name = "item_number", nullable = false)
  private Integer itemNumber;

  /**
   * Quantity of the product included on the invoice.
   */
  @Column(nullable = false)
  private Integer qty;

  /**
   * Discount value associated with the line item.
   */
  private Float discount;

  /**
   * Default constructor required by JPA.
   */
  public LineItem() {

  }

  // Accessor and mutator methods

  public Integer getLineItemId() {
    return lineItemId;
  }

  public void setLineItemId(Integer lineItemId) {
    this.lineItemId = lineItemId;
  }

  public Integer getInvoiceNumber() {
    return invoiceNumber;
  }

  public void setInvoiceNumber(Integer invoiceNumber) {
    this.invoiceNumber = invoiceNumber;
  }

  public Integer getItemNumber() {
    return itemNumber;
  }

  public void setItemNumber(Integer itemNumber) {
    this.itemNumber = itemNumber;
  }

  public Integer getQty() {
    return qty;
  }

  public void setQty(Integer qty) {
    this.qty = qty;
  }

  public Float getDiscount() {
    return discount;
  }

  public void setDiscount(Float discount) {
    this.discount = discount;
  }
}
