
package com.snhu.mscs.cs600.salesguru.sales;

/**
 * Imports to support Spring Data JPA entity mapping.
 */
import jakarta.persistence.Entity;
import jakarta.persistence.Table;
import jakarta.persistence.Id;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Column;

import java.time.LocalDate;

/**
 * Invoice -
 *
 * Purpose:
 *      Represents an invoice stored in the SalesGuru database.
 *      Each invoice is associated with a company, representative,
 *      and date of sale.
 *
 *      This class maps to the invoice table and supports the
 *      Sales Guru+ requirement to store invoices.
 *
 * Class Level Annotations:
 *      @Entity - Identifies this class as a JPA entity.
 *      @Table - Maps this entity to the invoice table.
 *
 * Expected Results:
 *      Invoice records can be retrieved and persisted using
 *      Spring Data JPA.
 *
 * Version              Author          Date            Description
 * ***********************************************************************
 *     1                 Chris Bright   17-Nov-2026     Initial Creation
 */
@Entity
@Table(name = "invoice")
public class Invoice {

  /**
   * invoiceNumber - Unique primary key generated by PostgreSQL.
   */
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  @Column(name = "invoice_number")
  private Integer invoiceNumber;

  /**
   * customerNumber - Identifies the company associated with the invoice.
   */
  @Column(name = "customer_number", nullable = false)
  private Integer customerNumber;

  /**
   * representativeId - Identifies the representative responsible for the sale.
   */
  @Column(name = "representative_id", nullable = false)
  private Integer representativeId;

  /**
   * dateOfSale - Date the sale was recorded.
   */
  @Column(name = "date_of_sale")
  private LocalDate dateOfSale;

  /**
   * lineItems - Stores the identifiers of associated invoice line items.
   * Invoice details will be retrieved from the line_items table.
   */
  @Column(name = "line_items", columnDefinition = "integer[]")
  private Integer[] lineItems;

  /**
   * Default constructor required by JPA.
   */
  public Invoice() {

  }

  /**
   * Accessor and mutator methods for the invoice attributes.
   */
  public Integer getInvoiceNumber() {
    return invoiceNumber;
  }

  public void setInvoiceNumber(Integer invoiceNumber) {
    this.invoiceNumber = invoiceNumber;
  }

  public Integer getCustomerNumber() {
    return customerNumber;
  }

  public void setCustomerNumber(Integer customerNumber) {
    this.customerNumber = customerNumber;
  }

  public Integer getRepresentativeId() {
    return representativeId;
  }

  public void setRepresentativeId(Integer representativeId) {
    this.representativeId = representativeId;
  }

  public LocalDate getDateOfSale() {
    return dateOfSale;
  }

  public void setDateOfSale(LocalDate dateOfSale) {
    this.dateOfSale = dateOfSale;
  }

  public Integer[] getLineItems() {
    return lineItems;
  }

  public void setLineItems(Integer[] lineItems) {
    this.lineItems = lineItems;
  }
}
