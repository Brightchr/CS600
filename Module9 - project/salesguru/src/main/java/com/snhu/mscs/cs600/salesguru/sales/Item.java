
package com.snhu.mscs.cs600.salesguru.sales;

/**
 * Imports to support Spring Data JPA entity mapping.
 */
import jakarta.persistence.Entity;
import jakarta.persistence.Table;
import jakarta.persistence.Id;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Column;

/**
 * Item -
 *
 * Purpose:
 *      Represents a product stored in the SalesGuru database.
 *      Each item contains a description, cost, and retail price.
 *
 *      This class maps to the items table and supports the
 *      Sales Guru+ requirement to store items for sale.
 *
 * Class Level Annotations:
 *      @Entity - Identifies this class as a JPA entity.
 *      @Table - Maps this entity to the items table.
 *
 * Expected Results:
 *      Item records can be retrieved and persisted using
 *      Spring Data JPA.
 *
 * Version              Author          Date            Description
 * ***********************************************************************
 *     1                 Chris Bright   17-Nov-2026     Initial Creation
 */
@Entity
@Table(name = "items")
public class Item {

  /**
   * itemNumber - Unique primary key generated by PostgreSQL.
   */
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  @Column(name = "item_number")
  private Integer itemNumber;

  /**
   * description - Description of the product being sold.
   */
  @Column(length = 128)
  private String description;

  /**
   * cost - Cost of the product.
   */
  private Float cost;

  /**
   * retail - Retail price of the product.
   */
  private Float retail;

  /**
   * Default constructor required by JPA.
   */
  public Item() {

  }

  /**
   * Accessor and mutator methods for the item's attributes.
   */
  public Integer getItemNumber() {
    return itemNumber;
  }

  public void setItemNumber(Integer itemNumber) {
    this.itemNumber = itemNumber;
  }

  public String getDescription() {
    return description;
  }

  public void setDescription(String description) {
    this.description = description;
  }

  public Float getCost() {
    return cost;
  }

  public void setCost(Float cost) {
    this.cost = cost;
  }

  public Float getRetail() {
    return retail;
  }

  public void setRetail(Float retail) {
    this.retail = retail;
  }
}
